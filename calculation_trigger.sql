DELIMITER $

CREATE TRIGGER trg_CALCULATE_TRIP_ACC_COST
BEFORE INSERT ON tripAccommodation 
FOR EACH ROW 
BEGIN
    DECLARE v_PRICE_PER_ROOM DECIMAL (10,2);
    DECLARE v_NIGHTS INT;

    SET v_NIGHTS = DATEDIFF(NEW.ta_CHECKOUT,NEW.ta_CHECKIN);
    SELECT acc_ROOM_PRICE INTO v_PRICE_PER_ROOM
    FROM accommodation WHERE acc_ID = NEW.ta_ACC_ID;

    SET NEW.ta_NIGHTS = v_NIGHTS;
    SET NEW.ta_COST = v_NIGHTS * NEW.ta_ROOMS * v_PRICE_PER_ROOM;

END $
DELIMITER ;